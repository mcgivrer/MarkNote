package ui;

/**
 * Positions de docking possibles pour un panel.
 */
public enum DockPosition {
    /** Zone haute de la fenêtre */
    TOP,
    /** Zone basse de la fenêtre */
    BOTTOM,
    /** Zone gauche de la fenêtre */
    LEFT,
    /** Zone droite de la fenêtre */
    RIGHT,
    /** Zone centrale (TabPane principal) */
    CENTER
}
